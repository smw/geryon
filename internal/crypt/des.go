func desCrypt(password, setting string) (string, error) {
	if len(setting) < 2 {
		return "", errors.New("salt too short")
	}

	// Key: the low 7 bits of each of the first 8 characters.
	var key [64]byte
	for i := 0; i < 8 && i < len(password); i++ {
		for j := 0; j < 7; j++ {
			key[i*8+j] = (password[i] >> (6 - j)) & 1
		}
	}

	// Key schedule.
	var cd [56]byte
	for i, p := range desPC1 {
		cd[i] = key[p-1]
	}
	var ks [16][48]byte
	for r := 0; r < 16; r++ {
		for s := byte(0); s < desShifts[r]; s++ {
			c0, d0 := cd[0], cd[28]
			copy(cd[0:27], cd[1:28])
			copy(cd[28:55], cd[29:56])
			cd[27], cd[55] = c0, d0
		}
		for i, p := range desPC2 {
			ks[r][i] = cd[p-1]
		}
	}

	// Salt-perturbed expansion table.
	e := desE
	for i := 0; i < 2; i++ {
		c := setting[i]
		if c > 'Z' {
			c -= 6
		}
		if c > '9' {
			c -= 7
		}
		c -= '.'
		for j := 0; j < 6; j++ {
			if (c>>j)&1 != 0 {
				e[6*i+j], e[6*i+j+24] = e[6*i+j+24], e[6*i+j]
			}
		}
	}

	var block [66]byte
	for n := 0; n < 25; n++ {
		var lr [64]byte
		for i, p := range desIP {
			lr[i] = block[p-1]
		}
		l, r := lr[:32], lr[32:]
		for round := 0; round < 16; round++ {
			var pre [48]byte
			for i := range pre {
				pre[i] = r[e[i]-1] ^ ks[round][i]
			}
			var f [32]byte
			for j := 0; j < 8; j++ {
				t := pre[6*j : 6*j+6]
				v := desS[j][t[0]<<5|t[5]<<4|t[1]<<3|t[2]<<2|t[3]<<1|t[4]]
				f[4*j] = (v >> 3) & 1
				f[4*j+1] = (v >> 2) & 1
				f[4*j+2] = (v >> 1) & 1
				f[4*j+3] = v & 1
			}
			var next [32]byte
			for i := range next {
				next[i] = l[i] ^ f[desP[i]-1]
			}
			copy(l, r)
			copy(r, next[:])
		}
		var pre [64]byte
		copy(pre[:32], r)
		copy(pre[32:], l)
		for i, p := range desFP {
			block[i] = pre[p-1]
		}
	}

	out := make([]byte, 13)
	out[0], out[1] = setting[0], setting[1]
	for i := 0; i < 11; i++ {
		var c byte
		for j := 0; j < 6; j++ {
			c = c<<1 | block[6*i+j]
		}
		c += '.'
		if c > '9' {
			c += 7
		}
		if c > 'Z' {
			c += 6
		}
		out[i+2] = c
	}
	return string(out), nil
}
